#!/bin/sh
# Точка входа контейнера: сначала индекс базы знаний, потом бот.
#
# Индекс пересобирается при каждом старте: так он всегда соответствует
# статьям, зашитым в образ. Это занимает секунды — модель эмбеддингов
# лежит в томе data/models/ и скачивается только при самом первом запуске.
set -e

echo "Собираю индекс базы знаний..."
python -m app.ingest

echo "Запускаю бота..."
exec python -m app.bot
